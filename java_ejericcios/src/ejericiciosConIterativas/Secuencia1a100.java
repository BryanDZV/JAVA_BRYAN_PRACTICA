package ejericiciosConIterativas;

public class Secuencia1a100 {

	public static void main(String[] args) {
		/*
		 * Secuencia1a100 Crea un algoritmo que nos muestre los números del 1 al 100,
		 * mediante una variable inicializada a 1
		 */
		
		for(int i=1;i<101;i++) {
			System.out.println("numero:  "+i);
		}

	}

}
