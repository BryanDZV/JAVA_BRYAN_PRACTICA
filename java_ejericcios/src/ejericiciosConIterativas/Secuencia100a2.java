package ejericiciosConIterativas;

public class Secuencia100a2 {

	public static void main(String[] args) {
		/*
		 * 11. Secuencia100a2 Crea un algoritmo que nos muestre los números pares desde
		 * el 100 hasta el 2 (decrementado de 2 en 2).
		 */
		
		for(int i=100; i>0;i-=2) {
			System.out.println(i);
		}

	}

}
