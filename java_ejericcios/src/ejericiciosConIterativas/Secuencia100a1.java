package ejericiciosConIterativas;

public class Secuencia100a1 {
	public static void main(String[] args) {
		/*
		 * Secuencia100a1 Crea un algoritmo que nos muestre los números del 100 al 1,
		 * mediante una variable inicializada a 100.
		 */
		
		for(int i=100; i>0;i--) {
			System.out.println(i);
		}
		

	}

}
